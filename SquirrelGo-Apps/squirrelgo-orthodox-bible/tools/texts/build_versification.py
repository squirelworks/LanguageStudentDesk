#!/usr/bin/env python3
"""Build www/data/versification.js from the Paratext/SIL versification files.

Each .vrs file maps its scheme's references onto the "original" (org)
scheme. eng.vrs is the English/KJV tradition, so a scheme's reference is
taken to KJV numbering by going scheme -> org -> eng. Only references whose
KJV equivalent differs are written. null means the verse has no KJV verse
of its own (a psalm title numbered as a verse, or a passage the KJV lacks).

Also checks every Bible already built in www/data/bibles and packs/bibles against the verse
counts of its scheme and reports chapters that disagree.
"""
import glob
import json
import os
import re
import sys

from common import CACHE, DATA, PACKS_DIR, book_ids

SCHEMES = {"lxx": "lxx.vrs", "rso": "rso.vrs", "vul": "vul.vrs", "org": "org.vrs"}


def parse_ref(s):
    """'PSA 9:22-39' -> list of (book, chapter, verse); also 'GEN 31:55-32:2'."""
    # Verse segments ("1:1a") are folded into their verse.
    m = re.match(r"([0-9A-Z]{3}) (\d+):(\d+)[a-z]?(?:-(?:(\d+):)?(\d+)[a-z]?)?$", s.strip())
    if not m:
        raise ValueError(s)
    b, c, v = m[1], int(m[2]), int(m[3])
    if m[5] is None:
        return [(b, c, v)]
    c2, v2 = int(m[4] or c), int(m[5])
    if c2 == c:
        return [(b, c, x) for x in range(v, v2 + 1)]
    return [(b, c, v), (b, c2, v2)]  # cross-chapter: only the ends are known


def parse_vrs(path):
    counts, mapping = {}, {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#")[0].strip() if not line.startswith("#") else ""
            if not line or line.startswith("-") or line.startswith("*"):
                continue
            if "=" in line:
                left, right = (parse_ref(x) for x in line.split("="))
                if len(left) == len(right):
                    pairs = zip(left, right)
                elif len(right) == 1:
                    pairs = ((l, right[0]) for l in left)
                else:
                    pairs = ((l, right[min(i, len(right) - 1)]) for i, l in enumerate(left))
                for l, r in pairs:
                    # "PSA 9:22 = PSA 10:0" followed by "PSA 9:22-39 = PSA 10:1-18":
                    # prefer a real verse over a title (verse 0).
                    if l not in mapping or (mapping[l][2] == 0 and r[2] != 0):
                        mapping[l] = r
                continue
            parts = line.split()
            if re.match(r"[0-9A-Z]{3}$", parts[0]):
                for cv in parts[1:]:
                    c, v = cv.split(":")
                    counts[(parts[0], int(c))] = int(v)
    return counts, mapping


def key(r):
    return "%s.%d.%d" % r


def build():
    vrs = os.path.join(CACHE, "vrs")
    eng_counts, eng_map = parse_vrs(os.path.join(vrs, "eng.vrs"))
    org_to_eng = {}
    for e, o in eng_map.items():
        org_to_eng.setdefault(o, e)

    def to_kjv(org):
        if org in org_to_eng:
            e = org_to_eng[org]
        elif org in eng_map:  # eng's verse of this number means something else
            return None
        elif (org[0], org[1]) in eng_counts and org[2] <= eng_counts[(org[0], org[1])]:
            e = org
        else:
            return org if (org[0], org[1]) not in eng_counts else None
        return None if e[2] == 0 else e

    known = set(book_ids())
    out, all_counts = {"kjv": {}}, {}
    for scheme, fname in SCHEMES.items():
        counts, mapping = parse_vrs(os.path.join(vrs, fname))
        all_counts[scheme] = counts
        refs = {(b, c, v) for (b, c), n in counts.items() for v in range(1, n + 1)}
        refs |= set(mapping)
        m = {}
        for r in sorted(refs, key=lambda r: (r[0], r[1], r[2])):
            if r[2] == 0 or r[0] not in known:  # DAG (Old Greek Daniel) etc.
                continue
            k = to_kjv(mapping.get(r, r))
            if k and k[0] not in known:  # e.g. Psalm 151 -> PS2, which KJV lacks
                k = None
            if k != r:
                m[key(r)] = key(k) if k else None
        out[scheme] = m
        print("%s: %d references differ from KJV" % (scheme, len(m)))
    all_counts["kjv"] = eng_counts

    path = os.path.join(DATA, "versification.js")
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Maps verse references from a translation's own numbering to KJV numbering,\n"
                "// listing only the references that differ. A null value means the verse has\n"
                "// no KJV verse of its own (for example a psalm title numbered as a verse).\n"
                "// Schemes: kjv (identity), lxx (Septuagint), rso (Russian Synodal / Slavonic),\n"
                "// vul (Vulgate), org (Hebrew: psalm titles as verses, Malachi in 3 chapters).\n"
                "// Generated by tools/texts/build_versification.py from the Paratext/SIL\n"
                "// standard versification files (lxx, rso, vul, org and eng .vrs).\n"
                "window.SGO_VERSIFICATION = ")
        f.write(json.dumps(out, ensure_ascii=False, indent=0, sort_keys=False).replace("\n", ""))
        f.write(";\n")
    print("wrote", path, "%.0f KB" % (os.path.getsize(path) / 1e3))
    return all_counts


def check(all_counts):
    """Report chapters whose verse count disagrees with the declared scheme."""
    for path in sorted(glob.glob(os.path.join(DATA, "bibles", "*.js"))
                       + glob.glob(os.path.join(PACKS_DIR, "bibles", "*.js"))):
        text = open(path, encoding="utf-8").read()
        obj = json.loads(text[text.index(".push(") + 6:text.rindex(");")])
        counts = all_counts.get(obj["versification"], {})
        bad = []
        for b, chapters in obj["books"].items():
            for i, verses in enumerate(chapters, 1):
                want = counts.get((b, i))
                if want is not None and len(verses) != want:
                    bad.append("%s %d (%d, scheme %d)" % (b, i, len(verses), want))
        print("%-22s %-4s %4d chapters differ from the scheme's verse counts%s" % (
            obj["id"], obj["versification"], len(bad), (": " + ", ".join(bad[:6])) if bad else ""))


if __name__ == "__main__":
    counts = build()
    if "--check" in sys.argv:
        check(counts)
