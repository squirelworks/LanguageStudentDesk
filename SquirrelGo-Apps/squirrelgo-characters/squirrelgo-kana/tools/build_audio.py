#!/usr/bin/env python3
"""Record every kana, example word and practice word in www/data/kana.js
with eSpeak NG's Japanese voice, so audio and the listening quiz work on a
phone with no Japanese text-to-speech voice installed.

For each script this records:
  - each lesson character (its speak text, which is the kana itself)
  - each character's example word
  - every data-text="…" in the script's articles (the practice words)

Clips go to www/audio/<script>/ as mono 32 kbps MP3, and a map from text to
clip goes to www/data/audio/<script>.js, which www/js/app.js checks before
falling back to the device voice. Each clip is named after a hash of what
was said, so a rerun only records what changed and removes clips no longer
used.

eSpeak reads the particles は and へ as ha and he, so in the practice
sentences (text with spaces) a word ending in は or へ is said with わ or え.

Needs espeak-ng, ffmpeg and node. Clips are committed; CI does not run this.

    python3 tools/build_audio.py
"""
import hashlib
import json
import os
import re
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
WWW = os.path.join(HERE, "..", "www")
VOICE = "ja"
SPEED = 130


def load_scripts():
    js = (
        "global.window=global;"
        "eval(require('fs').readFileSync(process.argv[1],'utf8').replace('const JA_FONT','var JA_FONT'));"
        "process.stdout.write(JSON.stringify(SG_SCRIPTS.map(s=>({id:s.id,title:s.title,"
        "chars:s.lessons.flatMap(l=>l.chars.filter(Boolean)),"
        "articles:(s.articles||[]).map(a=>a.body)}))))"
    )
    out = subprocess.run(["node", "-e", js, os.path.join(WWW, "data", "kana.js")], check=True, capture_output=True)
    return json.loads(out.stdout)


def spoken(text):
    """What eSpeak is asked to say for a text: particles fixed in sentences."""
    if " " not in text:
        return text
    return " ".join(re.sub(r"は$", "わ", re.sub(r"へ$", "え", w)) for w in text.split(" "))


def render(text, path):
    with tempfile.NamedTemporaryFile(suffix=".wav") as wav:
        subprocess.run(["espeak-ng", "-v", VOICE, "-s", str(SPEED), "-w", wav.name, text], check=True)
        subprocess.run(
            ["ffmpeg", "-loglevel", "error", "-y", "-i", wav.name,
             "-af", "silenceremove=start_periods=1:start_threshold=-50dB,areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse,apad=pad_dur=0.08",
             "-ac", "1", "-ar", "22050", "-b:a", "32k", path],
            check=True,
        )


def run(script):
    texts = []
    for c in script["chars"]:
        texts.append(c[6] if len(c) > 6 and c[6] else c[0])
        if len(c) > 3 and c[3]:
            texts.append(c[3])
    for body in script["articles"]:
        texts += re.findall(r'data-text="([^"]+)"', body)
    texts = list(dict.fromkeys(texts))

    out_dir = os.path.join(WWW, "audio", script["id"])
    os.makedirs(out_dir, exist_ok=True)
    clips, made = {}, 0
    for text in texts:
        said = spoken(text)
        name = hashlib.sha1(f"{VOICE}|{SPEED}|{said}".encode()).hexdigest()[:10] + ".mp3"
        path = os.path.join(out_dir, name)
        if not os.path.exists(path):
            render(said, path)
            made += 1
        clips[text] = name
    for f in os.listdir(out_dir):
        if f not in clips.values():
            os.remove(os.path.join(out_dir, f))

    os.makedirs(os.path.join(WWW, "data", "audio"), exist_ok=True)
    with open(os.path.join(WWW, "data", "audio", f"{script['id']}.js"), "w", encoding="utf-8") as f:
        f.write(
            f"// Recorded sounds for {script['title']}: spoken text -> clip in audio/{script['id']}/.\n"
            "// Generated by tools/build_audio.py with eSpeak NG.\n"
            "window.SG_AUDIO = window.SG_AUDIO || {};\n"
            f'window.SG_AUDIO["{script["id"]}"] = {{\n'
        )
        f.write(",\n".join(f"{json.dumps(t, ensure_ascii=False)}: {json.dumps(n)}" for t, n in clips.items()))
        f.write("\n};\n")
    print(f"{script['id']}: {len(clips)} clips ({made} new)")


if __name__ == "__main__":
    for s in load_scripts():
        run(s)
