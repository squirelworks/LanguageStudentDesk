#!/usr/bin/env python3
"""Rebuild languages/registry.js from languages/*/meta.json.

The learners read meta.json with fetch() when the Desk serves them over
http://. Browsers block fetch() of local files, so for file:// pages they fall
back to registry.js, a plain script with the same data. Run this after
editing any meta.json:

    python3 languages/build_registry.py          # rewrite registry.js
    python3 languages/build_registry.py --check  # exit 1 if it is stale
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def build():
    metas = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(HERE.glob("*/meta.json"))]
    body = json.dumps({m["id"]: m for m in metas}, ensure_ascii=False, indent=2)
    return ("// Generated by languages/build_registry.py from languages/*/meta.json. Do not edit.\n"
            "window.LSD_LANGUAGE_REGISTRY = " + body + ";\n")


def main():
    out = HERE / "registry.js"
    text = build()
    if "--check" in sys.argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("languages/registry.js is stale; run python3 languages/build_registry.py")
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    print("Wrote", out.relative_to(HERE.parent))
    return 0


if __name__ == "__main__":
    sys.exit(main())
